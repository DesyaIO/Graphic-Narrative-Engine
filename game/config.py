def get_full_path(filename: str) -> str:
    """Возвращает полный путь к файлу в директории данных"""
    import os
    return os.path.join(DATA_DIR, filename)


def get_save_path(slot_num: int) -> str:
    """Возвращает путь к файлу сохранения"""
    import os
    if not os.path.exists(SAVES_DIR):
        os.makedirs(SAVES_DIR)
    return os.path.join(SAVES_DIR, f"save_{slot_num}.json")


def validate_config() -> bool:
    """Проверяет корректность конфигурации"""
    import os

    errors = []

    # Проверка обязательных директорий
    required_dirs = [DATA_DIR, SAVES_DIR]
    for dir_path in required_dirs:
        if not os.path.exists(dir_path):
            try:
                os.makedirs(dir_path)
            except:
                errors.append(f"Не удалось создать директорию: {dir_path}")

    # Проверка основных значений
    if START_TIME >= DEADLINE_TIME:
        errors.append("Время старта должно быть раньше дедлайна")

    if MAX_PLAYER_SLOTS < 1:
        errors.append("Количество слотов сохранений должно быть положительным")

    return len(errors) == 0, errors


